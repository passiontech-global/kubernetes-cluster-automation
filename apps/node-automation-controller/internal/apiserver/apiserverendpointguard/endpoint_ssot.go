// endpoint_ssot.go — SSOT resolution of apiserver-endpoint-guard:
// which object carries the backend set + quarantine annotation this
// cluster (corev1 Endpoints vs discovery.k8s.io/v1 EndpointSlice).
// Slice discovery goes by the kubernetes.io/service-name=kubernetes
// label — the fixed "kubernetes" name exists only where the
// apiserver's own endpoint reconciler writes the slice; hosted
// control planes carry generated-name (kubernetes-xxxxx) mirror
// slices that are never the SSOT. The >=v1.33 version gate that
// promotes the slice to SSOT lives here too.
package apiserverendpointguard

