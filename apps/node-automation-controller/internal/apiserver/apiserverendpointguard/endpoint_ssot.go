// kubernetesSlices returns every EndpointSlice serving the kubernetes
// Service, sorted by name so epsList[0] is a stable "primary" for the
// quarantine annotation. The slice's name is fixed ("kubernetes") only
// where the apiserver's own endpoint reconciler writes it; hosted
// control planes carry generated-name mirror slices, so discovery goes
// by the service-name label. Slices mid-deletion are ignored.
func (g *apiServerEndpointGuard) kubernetesSlices(ctx context.Context) ([]*discoveryv1.EndpointSlice, error) {
	items, err := kube.ListAll(ctx,
		metav1.ListOptions{
			Limit:         kube.DefaultListPageSize,
			LabelSelector: endpointSliceServiceSelector},
		kube.EndpointSlices(g.cs, endpointGuardNS))
	if err != nil {
		return nil, err
	}
	out := make([]*discoveryv1.EndpointSlice, 0, len(items))
	for i := range items {
		if items[i].DeletionTimestamp == nil {
			out = append(out, &items[i])
		}
	}
	slices.SortFunc(out, func(a, b *discoveryv1.EndpointSlice) int {
		return strings.Compare(a.Name, b.Name)
	})
	return out, nil
}

// ssotPeerIPs discovers the IPs that are legitimately
// default/kubernetes backends from sources the guard NEVER mutates:
// the InternalIPs of control-plane nodes UNIONED with the
// high-water set of every backend IP that ever validly appeared in
// the kubernetes Endpoints/EndpointSlices (peerHighWater, recorded
// each sweep). On every self-hosted distro (kubeadm, k3s,
// k0s/k0smotron) the apiserver endpoints are control-plane node
// addresses, and hosted planes seed the same shape — a decommissioned
// backend's node disappears, so its IP leaves the node set and the
// re-add verdict can tell "we pulled it" apart from "it is gone".
// The high-water half covers the planes with NO control-plane Node
// objects at all (hosted control planes, workerless k0s
// controllers): there the node list yields nothing, but an IP the
// SSOT itself once carried is still proof the backend was real.
// Restricting the node half to CP nodes also keeps a deleted
// backend's IP from re-entering via reuse on a worker.
// P0-3: on hosted control planes no endpoint reconciler re-lists a
// quarantined IP, so the activeIPs membership check alone
// deadlocked recovered backends out of the set forever — this
// independent peer set is what lets them come back. Returns nil
// when BOTH sources are empty (node list failed or yielded no CP
// InternalIPs AND no backend IP was ever seen): callers treat that
// as "no peer evidence" and keep the reconciler-listing rule (fail
// closed — an unverifiable peer set never re-adds).
func (g *apiServerEndpointGuard) ssotPeerIPs(ctx context.Context) map[string]bool {
	set := map[string]bool{}
	// High-water first: it needs no API read at all.
	for ip := range g.peerHighWater {
		set[ip] = true
	}
	nodes, err := kube.ListNodes(ctx, g.cs)
	if err != nil {
		logf.FromContext(ctx).Error(err,
			"peer discovery failed — re-adds keep the reconciler-listing rule")
	} else {
		for i := range nodes {
			if !kube.IsControlPlane(&nodes[i]) {
				continue
			}
			for _, a := range nodes[i].Status.Addresses {
				if a.Type == corev1.NodeInternalIP && a.Address != "" {
					set[a.Address] = true
				}
			}
		}
	}
	if len(set) == 0 {
		return nil
	}
	return set
}

// mirrorManagedSlice reports whether the slice is generated by the
// endpointslicemirroring controller — a read-through projection of the
// Endpoints object (label managed-by, plus a controller ownerReference
// onto endpoints/kubernetes as belt&braces). A mirror is never the
// SSOT: its edits are rebuilt from the Endpoints object on the next
// mirror reconcile.
func mirrorManagedSlice(eps *discoveryv1.EndpointSlice) bool {
	if eps.Labels[discoveryv1.LabelManagedBy] == endpointSliceMirrorValue {
		return true
	}
	for _, r := range eps.OwnerReferences {
		if r.Kind == "Endpoints" && r.Controller != nil && *r.Controller {
			return true
		}
	}
	return false
}

func deepCopySlices(list []*discoveryv1.EndpointSlice) []*discoveryv1.EndpointSlice {
	out := make([]*discoveryv1.EndpointSlice, len(list))
	for i, s := range list {
		out[i] = s.DeepCopy()
	}
	return out
}

// slicesIPs unions the backend IPs across every resolved slice —
// dual-stack clusters carry one slice per address family.
func slicesIPs(list []*discoveryv1.EndpointSlice) []string {
	set := map[string]bool{}
	for _, s := range list {
		for _, ip := range sliceIPs(s) {
			set[ip] = true
		}
	}
	return slices.Sorted(maps.Keys(set))
}

// sliceIdxForIP picks the slice whose AddressType matches ip's family
// (re-adds must land in the same-family slice on dual-stack clusters);
// 0 falls back to the primary. -1 on an empty list.
func sliceIdxForIP(list []*discoveryv1.EndpointSlice, ip string) int {
	if len(list) == 0 {
		return -1
	}
	v6 := strings.Contains(ip, ":")
	for i, s := range list {
		if (s.AddressType == discoveryv1.AddressTypeIPv6) == v6 {
			return i
		}
	}
	return 0
}

