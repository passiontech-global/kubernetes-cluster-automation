#!/bin/sh
# gen-envdoc.sh — regenerate ENV.md, the operator-facing inventory of
# every NODE_HOST_AGENT_* knob the binary reads. The doc is derived,
# never hand-edited:
#
#   * the ENABLE_* tri-state gates come from the Descriptor registry
#     in cmd/agent/wiring.go (subsystem name + default mode included);
#   * every knob name is declared ONCE as an envnames.Env* const in
#     internal/envnames (the single source of truth for the env
#     contract) — call sites reference envnames.Env*, so each knob is
#     grouped under the package(s) that reference it, with the
#     file:line of the first reference. Stray "NODE_HOST_AGENT_*"
#     literals outside internal/envnames are picked up too, so a
#     missed refactor site still lands in the doc.
#
# Re-run: moon run node-host-agent:envdoc  (or: sh scripts/gen-envdoc.sh)
set -eu
cd "$(dirname "$0")/.."
export LC_ALL=C

out=ENV.md
rows=$(mktemp)
final=$(mktemp)
constmap=$(mktemp)
refs=$(mktemp)
trap 'rm -f "$rows" "$final" "$constmap" "$refs"' EXIT

# --- const -> var map: "EnvFoo<TAB>NODE_HOST_AGENT_FOO" -------------
# Every knob lives exactly once in internal/envnames as
# `EnvFoo = "NODE_HOST_AGENT_FOO"`.
rg -oN --no-heading '[A-Za-z0-9_]+[[:space:]]*=[[:space:]]*"NODE_HOST_AGENT_[A-Z0-9_]+"' \
	internal/envnames \
	| sed 's/^[^:]*://' \
	| awk -F= '{
		c = $1; gsub(/[[:space:]]/, "", c)
		v = $2; gsub(/[[:space:]"]/, "", v)
		print c "\t" v
	}' | sort >"$constmap"

# --- reference scan: "file:line:token" ------------------------------
# a) envnames.Env* references at call sites (the normal case),
# b) raw "NODE_HOST_AGENT_*" literals outside internal/envnames
#    (stragglers — kept so a missed literal still documents).
{
	rg -on --no-heading 'envnames\.Env[A-Za-z0-9_]+' \
		-g '*.go' -g '!*_test.go' -g '!internal/envnames/**' \
		cmd internal || true
	rg -on --no-heading '"NODE_HOST_AGENT_[A-Z0-9_]+"' \
		-g '*.go' -g '!*_test.go' -g '!internal/envnames/**' \
		cmd internal || true
} >"$refs"

# --- knob rows: "pkg-dir<TAB>VAR<TAB>file:line" ---------------------
awk -F: -v mapfile="$constmap" '
	BEGIN {
		while ((getline l < mapfile) > 0) {
			split(l, kv, "\t"); cmap[kv[1]] = kv[2]
		}
		close(mapfile)
	}
	{
		path = $1; ln = $2 + 0; tok = $3
		if (tok ~ /^envnames\./) {
			c = substr(tok, 10)
			if (!(c in cmap)) next      # non-name consts (Default*)
			var = cmap[c]
		} else {
			var = tok
			gsub(/"/, "", var)
		}
		# the ENABLE_* tri-state gates live in their own table
		if (var ~ /^NODE_HOST_AGENT_ENABLE_/) next
		n = split(path, a, "/"); base = a[n]
		dir = substr(path, 1, length(path) - length(base) - 1)
		k = dir SUBSEP var SUBSEP base
		# same var read twice in one file -> first location wins
		if (!(k in min) || ln < min[k]) min[k] = ln
	}
	END {
		for (k in min) {
			split(k, p, SUBSEP)
			printf "%s\t%s\t%s:%d\n", p[1], p[2], p[3], min[k]
		}
	}' "$refs" | sort -t '	' -k1,1 -k2,2 >"$rows"

nvars=$(cut -f2 "$rows" | sort -u | wc -l | tr -d ' ')
npkgs=$(cut -f1 "$rows" | sort -u | wc -l | tr -d ' ')

{
	cat <<HDR
# node-host-agent environment surface

_Generated by \`moon run node-host-agent:envdoc\`
(\`scripts/gen-envdoc.sh\`) — do not edit by hand._

Every \`NODE_HOST_AGENT_*\` knob the binary reads. Each name is
declared once as an \`envnames.Env*\` const in
\`internal/envnames\` (the single source of truth for the env
contract); call sites — \`envx.*\`/\`envx.*Knob\` declarations,
bespoke \`{Name: ...}\` knob rows and \`os.Getenv\`/\`getenv\`
calls in non-test \`*.go\` files — reference the const. The tables
below group knobs by the package(s) referencing them with the
source location of the first reference ($nvars knobs referenced
across $npkgs packages). The
\`NODE_HOST_AGENT_ENABLE_*\` tri-state gates live in their own table:
they come from the \`Descriptor\` registry, not a \`config_env.go\`.

## Enable gates (\`cmd/agent/wiring.go\`)

\`NODE_HOST_AGENT_ENABLE_*\` accepts \`true\` / \`false\` / \`auto\`
(\`envx.ModeEnv\` + the descriptor \`Default\`; \`ModeAuto\` resolves
through the descriptor's \`Auto\` func). \`onOff(w.defKube)\` reads
"on in pod mode, off in standalone". A \`—\` flag means the
subsystem has no env gate.

| Env var | Subsystem | Default |
| --- | --- | --- |
HDR

	# One row per descriptor: Name/EnvFlag/Default are emitted when the
	# block's Build: line is reached (every descriptor has a Build).
	# EnvFlag holds an envnames.Env* const — resolve it through the
	# const map (a bare "..." literal is still accepted).
	awk -v mapfile="$constmap" '
		BEGIN {
			while ((getline l < mapfile) > 0) {
				split(l, kv, "\t"); cmap[kv[1]] = kv[2]
			}
			close(mapfile)
		}
		/^[[:space:]]*Name:/    { match($0, /"[^"]+"/)
		                        name = substr($0, RSTART + 1, RLENGTH - 2) }
		/^[[:space:]]*EnvFlag:/ {
			if (match($0, /envnames\.[A-Za-z0-9_]+/)) {
				c = substr($0, RSTART + 9, RLENGTH - 9)
				flag = (c in cmap) ? cmap[c] : c
			} else if (match($0, /"[^"]+"/)) {
				flag = substr($0, RSTART + 1, RLENGTH - 2)
			}
		}
		/^[[:space:]]*Default:/ { d = $0
		                        sub(/.*Default:[[:space:]]*/, "", d)
		                        sub(/[[:space:]]*,.*/, "", d); def = d }
		/^[[:space:]]*Build:/   {
			f = (flag == "") ? "—" : "`" flag "`"
			v = (def  == "") ? "—" : "`" def "`"
			printf "| %s | %s | %s |\n", f, name, v
			name = flag = def = ""
		}
	' cmd/agent/wiring.go

	printf '\n## Knobs by package\n\n'

	awk -F'	' '{
		if ($1 != cur) {
			if (cur != "") print ""
			cur = $1
			printf "### `%s`\n\n", $1
		}
		print "- `" $2 "` — `" $3 "`"
	}' "$rows"

	printf '\n## Contract envs (not `NODE_HOST_AGENT_*`)\n\n'
	cat <<'CONTRACT'
Read directly, by contract — deliberately outside `internal/envnames`
(the env contract there covers the agent's own knobs only; these are
set by systemd or the k8s downward API):

| Env var | Set by | Read at |
| --- | --- | --- |
| `NODE_NAME` | k8s downward API (pod mode) | `cmd/agent` + `ops/hostconverge` via `platform/hostctx.NodeName` (`NODE_HOST_AGENT_NODE_NAME` > `NODE_NAME` > flag) |
| `POD_NAME` | k8s downward API (pod mode) | `cmd/agent` (pod identity, hubsync lease-holder) |
| `POD_NAMESPACE` | k8s downward API (pod mode) | `cmd/agent` |
| `NOTIFY_SOCKET` | systemd (standalone units) | `internal/agent/sdnotify.go` + `controllerhygiene/cdeps` (env knob row + feeder default) — via `platform/sdnotify.SocketEnv` |
| `KUBECONFIG` | operator (in-cluster fallback) | `cmd/agent/main.go` kube client factory |
CONTRACT
} >"$final"

mv "$final" "$out"
printf 'gen-envdoc: wrote %s (%s knobs, %s packages)\n' "$out" "$nvars" "$npkgs"
