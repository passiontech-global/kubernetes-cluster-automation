// genenvdoc renders ENV.md's enable-gates table to stdout — one row
// per Descriptor in cmd/agent/wiring.go (subsystem + default
// included), followed by any NODE_HOST_AGENT_ENABLE_* gate declared
// in internal/envnames but not wired as a descriptor
// (NODE_HOST_AGENT_ENABLE_FEEDER, read via envx.BoolKnob inside
// controllerhygiene), which gets an empty subsystem/default cell
// since it has no registry entry. scripts/gen-envdoc.sh splices the
// output into ENV.md's "## Enable gates" section between its prose
// header and the knob tables.
//
// Run via `moon run node-host-agent:envdoc` or:
//
//	go run ./internal/envdoc/cmd/genenvdoc -root <module-root>
//
// Parsing is AST-based (internal/envdoc/scan), so comments inside the
// registry cannot forge or split rows the way they could trip the
// line-based awk this replaces.
package main

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/passiontech-global/kubernetes-cluster-automation/apps/node-host-agent/internal/envdoc/scan"
)

// enablePrefix marks a contract value as an enable gate. Gates
// matching it that ScanGates did not find wired as a Descriptor
// EnvFlag are appended to the table.
const enablePrefix = "NODE_HOST_AGENT_ENABLE_"

// envDocHead is the ENV.md prologue through the gates-table header —
// @@ stands in for every markdown backtick (a Go raw literal cannot
// contain one) and the two %d verbs take the live knob/package
// counts. It is the heredoc the gen-envdoc.sh pipeline used to emit,
// verbatim.
const envDocHead = `# node-host-agent environment surface

_Generated by @@moon run node-host-agent:envdoc@@
(@@scripts/gen-envdoc.sh@@) — do not edit by hand._

Every @@NODE_HOST_AGENT_*@@ knob the binary reads. Each name is
declared once as an @@envnames.Env*@@ const in
@@internal/envnames@@ (the single source of truth for the env
contract); call sites — @@envx.*@@/@@envx.*Knob@@ declarations,
bespoke @@{Name: ...}@@ knob rows and @@os.Getenv@@/@@getenv@@
calls in non-test @@*.go@@ files — reference the const. The tables
below group knobs by the package(s) referencing them, listing the
source location of every reference in that package (%d knobs
referenced across %d packages). The
@@NODE_HOST_AGENT_ENABLE_*@@ tri-state gates live in their own table:
they come from the @@Descriptor@@ registry, not a @@config_env.go@@.

## Enable gates (@@cmd/agent/wiring.go@@)

@@NODE_HOST_AGENT_ENABLE_*@@ accepts @@true@@ / @@false@@ / @@auto@@
(@@envx.ModeEnv@@ + the descriptor @@Default@@; @@ModeAuto@@ resolves
through the descriptor's @@Auto@@ func). @@onOff(w.defKube)@@ reads
"on in pod mode, off in standalone". A @@—@@ flag means the
subsystem has no env gate.

| Env var | Subsystem | Default |
| --- | --- | --- |
`

// envDocTail is the contract-envs section closing the document —
// static by definition (the contract table is prose, not scanned
// data).
const envDocTail = `
## Contract envs (not @@NODE_HOST_AGENT_*@@)

Read directly, by contract — deliberately outside @@internal/envnames@@
(the env contract there covers the agent's own knobs only; these are
set by systemd or the k8s downward API):

| Env var | Set by | Read at |
| --- | --- | --- |
| @@NODE_NAME@@ | k8s downward API (pod mode) | @@cmd/agent@@ + @@ops/hostconverge@@ via @@platform/hostctx.NodeName@@ (@@NODE_HOST_AGENT_NODE_NAME@@ > @@NODE_NAME@@ > flag) |
| @@POD_NAME@@ | k8s downward API (pod mode) | @@cmd/agent@@ (pod identity, hubsync lease-holder) |
| @@POD_NAMESPACE@@ | k8s downward API (pod mode) | @@cmd/agent@@ |
| @@NOTIFY_SOCKET@@ | systemd (standalone units) | @@internal/agent/sdnotify.go@@ + @@controllerhygiene/cdeps@@ (env knob row + feeder default) — via @@platform/sdnotify.SocketEnv@@ |
| @@KUBECONFIG@@ | operator (in-cluster fallback) | @@cmd/agent/main.go@@ kube client factory |
`

func main() {
	// root is the node-host-agent module root; "." is right for
	// scripts/gen-envdoc.sh, which cds to the module root first.
	root := flag.String("root", ".", "node-host-agent module root")
	// write renders the FULL ENV.md (header + gates + knobs-by-
	// package + contract envs) to the named file at 0644 — the
	// pure-Go replacement for the rg|sed|awk pipeline the script
	// used to splice this generator's stdout into. Empty keeps the
	// original gates-table-to-stdout mode.
	write := flag.String("write", "", "write the complete ENV.md to this path (0664→0644)")
	flag.Parse()

	c, err := scan.CollectContract(*root)
	if err != nil {
		fatal(err)
	}
	gates, err := scan.ScanGates(*root, c)
	if err != nil {
		fatal(err)
	}

	if *write != "" {
		if err := writeEnvDoc(*root, *write, c, gates); err != nil {
			fatal(err)
		}
		return
	}

	var b strings.Builder
	renderGates(&b, c, gates)
	fmt.Print(b.String())
}

// writeEnvDoc renders the complete ENV.md — the same document
// scripts/gen-envdoc.sh's heredoc+awk pipeline produced, now
// entirely from the AST scans: header prose (with live knob/package
// counts), the gates table, the knobs-by-package reference table
// and the contract-envs tail. Written 0644 directly (mktemp staged
// 0600 and mv preserved it — the doc is operator-facing, not a
// secret).
func writeEnvDoc(root, out string, c scan.Contract, gates []scan.Gate) error {
	refs, err := scan.ScanSource(root, c)
	if err != nil {
		return err
	}

	// Knob rows: ENABLE_* values belong to the gates table only —
	// the awk pipeline filtered them before building rows. Counts
	// come from the same filtered set.
	vars := map[string]bool{}
	pkgs := map[string]bool{}
	for dir, byVar := range refs.PackageRefs {
		for v := range byVar {
			if strings.HasPrefix(v, enablePrefix) {
				continue
			}
			vars[v] = true
			pkgs[dir] = true
		}
	}

	var b strings.Builder
	// envDocHead carries @@ for every markdown backtick — a raw
	// literal cannot contain one, and hand-concatenating ~40
	// inline-code spans is where the escapes went wrong before.
	// %d verbs take the live knob/package counts.
	head := strings.ReplaceAll(envDocHead, "@@", "`")
	fmt.Fprintf(&b, head, len(vars), len(pkgs))

	renderGates(&b, c, gates)

	b.WriteString("\n## Knobs by package\n")
	dirs := make([]string, 0, len(refs.PackageRefs))
	for dir := range refs.PackageRefs {
		dirs = append(dirs, dir)
	}
	slices.Sort(dirs)
	for _, dir := range dirs {
		byVar := refs.PackageRefs[dir]
		names := make([]string, 0, len(byVar))
		for v := range byVar {
			if !strings.HasPrefix(v, enablePrefix) {
				names = append(names, v)
			}
		}
		if len(names) == 0 {
			continue
		}
		slices.Sort(names)
		// The leading \n in the ### line IS the section separator —
		// one blank line after the heading and between packages.
		fmt.Fprintf(&b, "\n### `%s`\n\n", dir)
		for _, v := range names {
			files := byVar[v]
			sites := make([]string, 0, len(files))
			for f, ln := range files {
				sites = append(sites, fmt.Sprintf("%s:%d", f, ln))
			}
			slices.Sort(sites)
			fmt.Fprintf(&b, "- `%s` — `%s`\n", v, strings.Join(sites, ", "))
		}
	}

	b.WriteString(strings.ReplaceAll(envDocTail, "@@", "`"))

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "genenvdoc: wrote %s (%d knobs, %d packages)\n",
		out, len(vars), len(pkgs))
	return nil
}

// renderGates writes the enable-gates table rows — the same emit
// sequence main's stdout mode prints, shared so -write cannot drift
// from the splice mode.
func renderGates(b *strings.Builder, c scan.Contract, gates []scan.Gate) {
	wired := map[string]bool{}
	for _, g := range gates {
		wired[g.EnvFlag] = true
	}
	var unwired []string
	for v := range c.Values {
		if strings.HasPrefix(v, enablePrefix) && !wired[v] {
			unwired = append(unwired, v)
		}
	}
	slices.Sort(unwired)
	for _, g := range gates {
		emitRow(b, g.EnvFlag, g.Name, g.Default)
	}
	for _, v := range unwired {
		emitRow(b, v, "", "")
	}
}

// defaultCell renders the Default expression as the VALUE it
// resolves to — the raw wiring.go selector text (`envx.ModeOn`,
// `onOff(w.defKube)`) is plumbing, not an operator fact. The three
// envx mode spellings map to their tri-state word; the defKube flip
// (pod mode on, standalone off) renders both faces. Anything else
// falls back to the verbatim expression so an unrecognized shape
// still lands in the doc.
func defaultCell(def string) string {
	switch def {
	case "envx.ModeOn":
		return "`on`"
	case "envx.ModeOff":
		return "`off`"
	case "envx.ModeAuto":
		return "`auto`"
	case "onOff(w.defKube)":
		return "`on` (pod) / `off` (standalone)"
	case "":
		return "—"
	default:
		return "`" + def + "`"
	}
}

// emitRow appends one markdown table row to b; an empty env var,
// subsystem or default renders as "—" (hubsync has no env gate,
// some descriptors no default), matching the doc's existing
// convention.
func emitRow(b *strings.Builder, envFlag, subsystem, def string) {
	if envFlag == "" {
		envFlag = "—"
	} else {
		envFlag = "`" + envFlag + "`"
	}
	if subsystem == "" {
		subsystem = "—"
	}
	fmt.Fprintf(b, "| %s | %s | %s |\n", envFlag, subsystem, defaultCell(def))
}

// fatal reports a scanner failure on stderr and exits nonzero — the
// calling script runs with `set -e`, so ENV.md is left untouched.
func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genenvdoc:", err)
	os.Exit(1)
}
